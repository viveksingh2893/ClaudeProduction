async function main() {
  const adapter = new PrismaPg({ connectionString: process.env.DATABASE_URL });
  const prisma = new PrismaClient({ adapter });

  let written = 0;
  for (const product of SAMPLE) {
    const exists = await prisma.product.findUnique({
      where: { id: product.id },
      select: { id: true, name: true },
    });
    if (!exists) {
      console.warn(`skip ${product.id} (${product.label}) — not on this database`);
      continue;
    }
    for (const lang of ["HI", "MR", "TE", "TA"] as const) {
      const f = product.tr[lang];
      const data = {
        name: f.name.trim() || null,
        shortDescription: f.shortDescription.trim() || null,
        description: f.description.trim() || null,
        ingredients: f.ingredients.trim() || null,
        howToUse: f.howToUse.trim() || null,
        dosageInstructions: f.dosageInstructions.trim() || null,
        technicalInfo: f.technicalInfo.trim() || null,
      };
      await prisma.productTranslation.upsert({
        where: { productId_language: { productId: product.id, language: lang } },
        create: { productId: product.id, language: lang, ...data },
        update: data,
      });
      written++;
      console.log(`${exists.name.slice(0, 45).padEnd(45)} → ${lang}  ✓`);
    }
  }
  console.log(`\n${written} ProductTranslation rows written across ${SAMPLE.length} products.`);
  await prisma.$disconnect();
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
