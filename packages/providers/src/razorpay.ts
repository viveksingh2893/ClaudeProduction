/**
 * Razorpay integration — the second real (non-mock) third-party provider
 * in this package, after rapidshyp.ts. Same deliberate-exception status:
 * a real payment gateway brought in once real checkout collection was
 * actually needed, replacing payment.ts's mock provider for self-service
 * (non-POS) online payments — see packages/orders/src/checkout.ts's
 * applyInitialPayment for exactly where the split happens.
 *
 * Test mode vs. live mode is purely which key pair is configured
 * (`rzp_test_...` vs `rzp_live_...`) — same API, same code path, no
 * separate sandbox URL. Docs: https://razorpay.com/docs/api/.
 *
 * Auth is HTTP Basic (key_id as username, key_secret as password) — a
 * different scheme from rapidshyp.ts's custom header, per Razorpay's own
 * convention.
 */
import { createHmac, timingSafeEqual } from "node:crypto";

const RAZORPAY_BASE_URL = "https://api.razorpay.com/v1/";

function credentials(): { keyId: string; keySecret: string } {
  const keyId = process.env.RAZORPAY_KEY_ID;
  const keySecret = process.env.RAZORPAY_KEY_SECRET;
  if (!keyId || !keySecret) throw new Error("RAZORPAY_KEY_ID / RAZORPAY_KEY_SECRET are not configured.");
  return { keyId, keySecret };
}

export type RazorpayResult<T> =
  | { ok: true; data: T; raw: unknown }
  | { ok: false; error: string; raw: unknown };

async function razorpayRequest(
  path: string,
  method: "GET" | "POST",
  body?: unknown,
): Promise<{ raw: unknown; httpOk: boolean }> {
  const { keyId, keySecret } = credentials();
  const auth = Buffer.from(`${keyId}:${keySecret}`).toString("base64");
  let res: Response;
  try {
    res = await fetch(`${RAZORPAY_BASE_URL}${path}`, {
      method,
      headers: { Authorization: `Basic ${auth}`, "Content-Type": "application/json" },
      body: body ? JSON.stringify(body) : undefined,
    });
  } catch {
    return { raw: null, httpOk: false };
  }
  const raw = await res.json().catch(() => null);
  return { raw, httpOk: res.ok };
}

function asString(v: unknown): string | undefined {
  return typeof v === "string" ? v : undefined;
}

function errorMessage(raw: unknown): string {
  if (raw && typeof raw === "object" && "error" in raw) {
    const err = (raw as { error?: { description?: string } }).error;
    if (err?.description) return err.description;
  }
  return "Razorpay reported an error.";
}

/**
 * Rupees -> paise, the integer unit Razorpay's API requires everywhere
 * (amount fields, refund amounts). Rounds to the nearest paise rather than
 * truncating — the same "never silently lose a fraction of a rupee"
 * discipline packages/orders/src/money.ts's round2 already follows for
 * rupee amounts.
 */
export function toPaise(rupees: number): number {
  return Math.round(rupees * 100);
}

export interface RazorpayOrder {
  id: string;
  amount: number; // paise
  currency: string;
}

/**
 * Creates the Order a customer's Checkout widget session opens against.
 * `receipt` is our own reference (Payment.internalReference) — shown back
 * to us, never generated by Razorpay. Idempotent per Razorpay's own
 * `receipt` + amount + currency dedup (a retried create_order with the
 * same receipt returns the existing order rather than a duplicate) —
 * relevant since applyInitialPayment can, in principle, be retried.
 */
export async function razorpayCreateOrder(input: {
  amountRupees: number;
  receipt: string;
  notes?: Record<string, string>;
}): Promise<RazorpayResult<RazorpayOrder>> {
  const { raw, httpOk } = await razorpayRequest("orders", "POST", {
    amount: toPaise(input.amountRupees),
    currency: "INR",
    receipt: input.receipt,
    notes: input.notes,
  });
  if (!httpOk) return { ok: false, error: errorMessage(raw), raw };
  const r = raw as Record<string, unknown>;
  const id = asString(r.id);
  if (!id) return { ok: false, error: "Razorpay did not return an order id.", raw };
  return {
    ok: true,
    data: { id, amount: Number(r.amount), currency: asString(r.currency) ?? "INR" },
    raw,
  };
}

/**
 * The client-callback signature check (Checkout widget's own success
 * handler gives back order_id + payment_id + signature) — per Razorpay's
 * documented formula: HMAC-SHA256(order_id + "|" + payment_id, key_secret).
 * Never trust a client callback without this; see completeRazorpayPayment
 * (packages/orders/src/checkout.ts) for where it's enforced, and note it
 * still isn't the ONLY check there — a live fetch against Razorpay
 * confirms the payment actually shows "captured" too.
 */
export function verifyPaymentSignature(input: {
  orderId: string;
  paymentId: string;
  signature: string;
}): boolean {
  const { keySecret } = credentials();
  const expected = createHmac("sha256", keySecret)
    .update(`${input.orderId}|${input.paymentId}`)
    .digest("hex");
  return safeCompare(expected, input.signature);
}

/**
 * Webhook payload signature check — a SEPARATE secret from key_secret
 * (configured in the Razorpay Dashboard's Webhooks section against a
 * specific webhook URL, e.g. this app's /api/webhooks/razorpay). Must be
 * computed over the exact raw request body bytes, before any JSON
 * parsing/reserialization — reserializing first is a common way this
 * check silently always fails.
 */
export function verifyWebhookSignature(rawBody: string, signature: string): boolean {
  const secret = process.env.RAZORPAY_WEBHOOK_SECRET;
  if (!secret) return false;
  const expected = createHmac("sha256", secret).update(rawBody).digest("hex");
  return safeCompare(expected, signature);
}

function safeCompare(a: string, b: string): boolean {
  const bufA = Buffer.from(a);
  const bufB = Buffer.from(b);
  if (bufA.length !== bufB.length) return false;
  return timingSafeEqual(bufA, bufB);
}

export interface RazorpayPaymentDetail {
  id: string;
  status: string; // "created" | "authorized" | "captured" | "refunded" | "failed"
  amount: number; // paise
  orderId?: string;
}

/**
 * A live server-side read of a payment's current state — the belt to
 * verifyPaymentSignature's suspenders. The signature alone proves the
 * callback came from Razorpay; this confirms what it's actually reporting
 * still holds (status genuinely "captured", not e.g. later reversed)
 * before treating an order as paid.
 */
export async function razorpayFetchPayment(
  paymentId: string,
): Promise<RazorpayResult<RazorpayPaymentDetail>> {
  const { raw, httpOk } = await razorpayRequest(`payments/${paymentId}`, "GET");
  if (!httpOk) return { ok: false, error: errorMessage(raw), raw };
  const r = raw as Record<string, unknown>;
  const id = asString(r.id);
  const status = asString(r.status);
  if (!id || !status) return { ok: false, error: "Unexpected response from Razorpay.", raw };
  return {
    ok: true,
    data: { id, status, amount: Number(r.amount), orderId: asString(r.order_id) },
    raw,
  };
}

export interface RazorpayRefund {
  id: string;
  status: string;
}

/**
 * Refunds against a real captured payment — full or partial (partial is
 * just `amountRupees` less than what was originally captured; Razorpay
 * allows multiple partial refunds against one payment up to its total).
 * See packages/orders/src/refunds.ts's completeRefund for the ORIGINAL_SOURCE
 * branch this backs.
 */
export async function razorpayCreateRefund(input: {
  paymentId: string;
  amountRupees: number;
  notes?: Record<string, string>;
}): Promise<RazorpayResult<RazorpayRefund>> {
  const { raw, httpOk } = await razorpayRequest(`payments/${input.paymentId}/refund`, "POST", {
    amount: toPaise(input.amountRupees),
    notes: input.notes,
  });
  if (!httpOk) return { ok: false, error: errorMessage(raw), raw };
  const r = raw as Record<string, unknown>;
  const id = asString(r.id);
  const status = asString(r.status);
  if (!id) return { ok: false, error: "Razorpay did not return a refund id.", raw };
  return { ok: true, data: { id, status: status ?? "processed" }, raw };
}
