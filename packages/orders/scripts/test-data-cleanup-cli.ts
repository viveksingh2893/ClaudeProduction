/**
 * Test-data cleanup — dry-run / manifest / apply, in that order, per the
 * safe-cleanup requirement ("a mandatory preview and approval process").
 *
 * Usage (via pnpm --filter @kisan4u/orders test-data-cleanup:*):
 *   preview                          — dry-run report only (default; safe, read-only)
 *   manifest [--out <path>]          — writes the approval manifest JSON (still read-only)
 *   apply --apply --manifest <path>  — the ONLY command that writes anything
 *
 * No subcommand defaults to `preview` — dry run is always the default
 * behaviour, per spec. Lives in packages/orders (not packages/db, despite
 * being a database-wide cleanup) because it needs @kisan4u/catalog's
 * existing deleteProduct/removeVariant domain services — packages/db
 * cannot depend on packages/catalog (catalog depends on db, not the
 * reverse), so this is the correct home, matching this package's existing
 * scripts/backfill-seller-settlements.ts's own "scripts/ = thin CLI,
 * src/ = the real logic" convention.
 */
import "dotenv/config";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { prisma } from "@kisan4u/db";
import { identifyEnvironment } from "../src/test-data-cleanup/environment";
import { runDiscovery } from "../src/test-data-cleanup/discovery";
import { printReport } from "../src/test-data-cleanup/report";
import {
  buildManifest,
  verifyManifestChecksum,
  diffManifestAgainstFresh,
  type Manifest,
} from "../src/test-data-cleanup/manifest";
import { createBackup } from "../src/test-data-cleanup/backup";
import { applyManifest } from "../src/test-data-cleanup/apply";

const args = process.argv.slice(2);
const command = args[0] && !args[0].startsWith("--") ? args[0] : "preview";
const APPLY_FLAG = args.includes("--apply");
const manifestPathArg = args.find((a) => a.startsWith("--manifest="))?.split("=")[1];
const outArg = args.find((a) => a.startsWith("--out="))?.split("=")[1];

const DEFAULT_MANIFEST_DIR = path.join(process.cwd(), "test-data-cleanup-output", "manifests");
const DEFAULT_BACKUP_DIR = path.join(process.cwd(), "test-data-cleanup-output", "backups");

function printEnvironmentBanner(): void {
  const env = identifyEnvironment(process.env.DATABASE_URL);
  console.log("=== Environment identity (credentials never shown) ===");
  console.log(`  host: ${env.host}`);
  console.log(`  port: ${env.port}`);
  console.log(`  database: ${env.database}`);
  console.log(`  heuristic guess: ${env.guess} (a heuristic on the database name only — confirm before relying on it)`);
  console.log("");
}

async function cmdPreview(): Promise<void> {
  printEnvironmentBanner();
  const { groups } = await runDiscovery();
  printReport(groups);
}

async function cmdManifest(): Promise<void> {
  printEnvironmentBanner();
  const env = identifyEnvironment(process.env.DATABASE_URL);
  const { groups, allCandidates } = await runDiscovery();
  printReport(groups);

  const manifest = buildManifest(`${env.database}@${env.host}:${env.port} (${env.guess})`, allCandidates);
  const outPath = outArg ?? path.join(DEFAULT_MANIFEST_DIR, `manifest-${manifest.generatedAt.replace(/[:.]/g, "-")}.json`);
  await mkdir(path.dirname(outPath), { recursive: true });
  await writeFile(outPath, JSON.stringify(manifest, null, 2), "utf8");

  console.log(`\n=== Manifest written ===`);
  console.log(`  path: ${outPath}`);
  console.log(`  generatedAt: ${manifest.generatedAt}`);
  console.log(`  environment: ${manifest.environment}`);
  console.log(`  entries: ${manifest.entries.length}`);
  console.log(`  checksum: ${manifest.checksum}`);
  console.log(`\nThis manifest is NOT applied. Review it, then re-run with:`);
  console.log(`  pnpm --filter @kisan4u/orders test-data-cleanup:apply -- --apply --manifest=${outPath}`);
}

async function cmdApply(): Promise<void> {
  printEnvironmentBanner();
  if (!APPLY_FLAG) {
    console.log("Refusing to apply — pass --apply explicitly.");
    process.exitCode = 1;
    return;
  }
  if (!manifestPathArg) {
    console.log("Refusing to apply — pass --manifest=<path to a manifest generated by the `manifest` command>.");
    process.exitCode = 1;
    return;
  }

  const raw = await readFile(manifestPathArg, "utf8").catch(() => null);
  if (!raw) {
    console.log(`Refusing to apply — could not read manifest file ${manifestPathArg}.`);
    process.exitCode = 1;
    return;
  }
  const manifest: Manifest = JSON.parse(raw);
  if (!verifyManifestChecksum(manifest)) {
    console.log("Refusing to apply — manifest checksum does not match its own contents (file corrupted or hand-edited). Generate a fresh manifest.");
    process.exitCode = 1;
    return;
  }

  const env = identifyEnvironment(process.env.DATABASE_URL);
  if (env.guess === "production") {
    const confirmFlag = args.includes("--confirm-production");
    if (!confirmFlag) {
      console.log(
        `Refusing to apply — this environment looks like PRODUCTION (database name contains "prod"). Re-run with --confirm-production added if this is genuinely intended.`,
      );
      process.exitCode = 1;
      return;
    }
  }

  console.log("Re-scanning the live database to check the manifest hasn't gone stale...");
  const fresh = await runDiscovery();
  const problems = diffManifestAgainstFresh(manifest, fresh.allCandidates);
  if (problems.length > 0) {
    console.log(`\nRefusing to apply — the manifest is stale (${problems.length} problem(s)):`);
    for (const p of problems) console.log(`  - ${p}`);
    console.log("\nGenerate a fresh manifest and review it again.");
    process.exitCode = 1;
    return;
  }
  console.log("Manifest still matches a fresh scan exactly. Proceeding to backup.\n");

  const databaseUrl = process.env.DATABASE_URL;
  if (!databaseUrl) {
    console.log("Refusing to apply — DATABASE_URL is not set.");
    process.exitCode = 1;
    return;
  }
  console.log("Creating a verified backup before touching anything...");
  const backup = await createBackup(databaseUrl, DEFAULT_BACKUP_DIR);
  if (!backup.ok) {
    console.log(`Refusing to apply — backup failed: ${backup.error}`);
    process.exitCode = 1;
    return;
  }
  console.log(`Backup verified: ${backup.filePath} (${backup.sizeBytes} bytes)\n`);

  console.log(`Applying ${manifest.entries.length} approved deletion(s)...`);
  const outcomes = await applyManifest(manifest);
  const succeeded = outcomes.filter((o) => o.ok);
  const failed = outcomes.filter((o) => !o.ok);

  console.log("\n=== Apply results ===");
  for (const o of outcomes) {
    console.log(`  ${o.ok ? "✔" : "✖"} ${o.entry.entityType} ${o.entry.id} "${o.entry.name}" — ${o.detail}`);
  }
  console.log(`\nSucceeded: ${succeeded.length}/${outcomes.length}. Failed: ${failed.length}.`);
  console.log(`Backup: ${backup.filePath}`);
  if (failed.length > 0) process.exitCode = 1;
}

async function main() {
  if (command === "preview") await cmdPreview();
  else if (command === "manifest") await cmdManifest();
  else if (command === "apply") await cmdApply();
  else {
    console.log(`Unknown command "${command}". Use one of: preview (default), manifest, apply.`);
    process.exitCode = 1;
  }
}

main()
  .catch((err) => {
    console.error(err);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
